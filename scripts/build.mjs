// Production build: bundles src/platform/web/main.js with esbuild and inlines it into the page from
// src/index.html. Outputs (both GENERATED, never edit them):
//   index.html             — self-contained page; works from any static host and when opened directly (file://)
//   dist/villa-limon.html  — the same without <html>/<head>/<body>, for hosts that wrap pages (claude.ai artifact)
// Three.js still comes from the CDN import map.
import { build } from 'esbuild';
import fs from 'node:fs';

const root = new URL('..', import.meta.url).pathname;
const out = await build({
  entryPoints: [root + 'src/platform/web/main.js'], bundle: true, format: 'esm', target: 'es2020', minify: true, write: false,
  external: ['three', 'three/addons/*'], legalComments: 'none',
});
const js = out.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const page = fs.readFileSync(root + 'src/index.html', 'utf8');
const marker = /<!-- build:main -->[\s\S]*?<!-- \/build:main -->/;
if (!marker.test(page)) throw new Error('src/index.html lost its build:main marker');
let html = page.replace(marker, () => `<script type="module">${js}</script>`);
const full = html.replace(/<!doctype html>/i, '<!doctype html>\n<!-- GENERATED by `npm run build` from src/index.html and src/. Do not edit. -->');
fs.writeFileSync(root + 'index.html', full);
// The artifact host wraps the page in its own document: keep the content, drop the outer document tags.
const fragment = html.replace(/<!doctype html>\s*/i, '').replace(/<\/?(html|head|body)(\s[^>]*)?>\s*/gi, '');
fs.mkdirSync(root + 'dist', { recursive: true });
fs.writeFileSync(root + 'dist/villa-limon.html', fragment);
console.log(`built index.html (${(full.length / 1024).toFixed(0)} KB) and dist/villa-limon.html`);
